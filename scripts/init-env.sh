#!/usr/bin/env bash
# Generates a local .env with strong random secrets and an RS256 key pair for JWT signing.
# Safe to re-run: existing files are kept unless --force is given. Secrets are never printed.
set -euo pipefail
cd "$(dirname "$0")/.."

FORCE=false
[[ "${1:-}" == "--force" ]] && FORCE=true

rand() { openssl rand -hex "${1:-24}"; }

umask 077
if [[ -f .env && "$FORCE" == false ]]; then
  echo ".env already exists — keeping existing values and adding only missing keys (use --force to regenerate all;"
  echo "that invalidates existing database passwords, so also run ./scripts/reset-data.sh)."
else
  echo "# Generated by scripts/init-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Do not commit." > .env
fi
ADDED=0
# put KEY VALUE — appends KEY=VALUE unless KEY is already defined (existing values are never changed)
put() {
  if ! grep -qE "^$1=" .env; then
    printf '%s=%s\n' "$1" "$2" >> .env
    ADDED=$((ADDED + 1))
  fi
}
put POSTGRES_ADMIN_USER grandvista_admin
put POSTGRES_ADMIN_PASSWORD "$(rand)"
put AUTH_DB_PASSWORD "$(rand)"
put ROOM_DB_PASSWORD "$(rand)"
put BOOKING_DB_PASSWORD "$(rand)"
put PAYMENT_DB_PASSWORD "$(rand)"
put NOTIFICATION_DB_PASSWORD "$(rand)"
put AUTH_DB_HOST_PORT 5433
put ROOM_DB_HOST_PORT 5434
put BOOKING_DB_HOST_PORT 5435
put PAYMENT_DB_HOST_PORT 5436
put NOTIFICATION_DB_HOST_PORT 5437
put RABBITMQ_USERNAME grandvista
put RABBITMQ_PASSWORD "$(rand)"
put EUREKA_USERNAME eureka
put EUREKA_PASSWORD "$(rand)"
put BOOKING_SERVICE_CLIENT_SECRET "$(rand 32)"
put PAYMENT_SERVICE_CLIENT_SECRET "$(rand 32)"
put ROOM_SERVICE_CLIENT_SECRET "$(rand 32)"
put PAYMENT_WEBHOOK_SECRET "$(rand 32)"
put GV_BOOTSTRAP_ADMIN_EMAIL admin@grandvista.local
put GV_BOOTSTRAP_ADMIN_PASSWORD "$(rand 12)"
put GV_DEMO_CUSTOMER_EMAIL guest@grandvista.local
put GV_DEMO_CUSTOMER_PASSWORD "Guest-$(rand 6)-7"
put GV_DEMO_STAFF_EMAIL staff@grandvista.local
put GV_DEMO_STAFF_PASSWORD "Staff-$(rand 6)-7"
put GRAFANA_ADMIN_PASSWORD "$(rand 12)"
put GV_DOMAIN ""
put ACME_EMAIL ""
put GV_PAYMENT_PROVIDER simulated
put RAZORPAY_KEY_ID ""
put RAZORPAY_KEY_SECRET ""
put RAZORPAY_WEBHOOK_SECRET ""
put GV_HOTEL_ZONE Asia/Kolkata
put GV_DEMO_SEED_ENABLED true
put GV_HOLD_TTL 15m
put API_DOCS_ENABLED true
put GV_COOKIE_SECURE true
put GV_CORS_ALLOWED_ORIGINS http://localhost:3000,http://localhost:5173
put GATEWAY_HOST_PORT 8080
put FRONTEND_HOST_PORT 3000
chmod 600 .env
echo "Wrote .env (permissions 600): $ADDED key(s) added. Passwords for the administrator and demo accounts are"
echo "stored there (GV_BOOTSTRAP_ADMIN_PASSWORD, GV_DEMO_CUSTOMER_PASSWORD, GV_DEMO_STAFF_PASSWORD); they are not printed."

SECRETS=infrastructure/secrets
mkdir -p "$SECRETS"
chmod 700 "$SECRETS"
if [[ -f "$SECRETS/jwt-private.pem" && "$FORCE" == false ]]; then
  echo "JWT key pair already exists — keeping it."
else
  openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:2048 -out "$SECRETS/jwt-private.pem" 2>/dev/null
  openssl pkey -in "$SECRETS/jwt-private.pem" -pubout -out "$SECRETS/jwt-public.pem"
  # Readable by the container's non-root user; the 700 directory keeps other host users out.
  chmod 644 "$SECRETS/jwt-private.pem" "$SECRETS/jwt-public.pem"
  echo "Generated RS256 key pair in $SECRETS/ (git-ignored)."
fi
